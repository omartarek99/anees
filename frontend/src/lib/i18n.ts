/** Picks the Arabic variant of a bilingual content field when in Arabic mode (falls back to English if missing). */
export function pickText(lang: Lang, en: string, ar?: string | null): string {
  return lang === 'ar' && ar ? ar : en;
}

export function translateApiError(lang: Lang, message: string): string {
  if (lang === 'en') return message;
  return apiErrorMap[message] ?? message;
}
