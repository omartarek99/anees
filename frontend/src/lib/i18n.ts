export const dictionaries: Record<Lang, typeof en> = { en, ar };

function getByPath(obj: any, path: string): string | undefined {
  return path.split('.').reduce((acc, key) => (acc && typeof acc === 'object' ? acc[key] : undefined), obj);
}

export function translate(lang: Lang, path: string, vars?: Record<string, string | number>): string {
  const dict = dictionaries[lang];
  let value = getByPath(dict, path) ?? getByPath(dictionaries.en, path) ?? path;
  if (vars) {
    for (const [key, val] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${key}\\}`, 'g'), String(val));
    }
  }
  return value;
}

